function [args, accepted] = cleanline_integrated_dialog(EEG)
%CLEANLINE_INTEGRATED_DIALOG Single-window settings for all CleanLine engines.
args = {};
accepted = false;
navy = [0.055 0.12 0.21];
panel = [0.10 0.18 0.28];
white = [0.94 0.97 0.98];
teal = [0.27 0.80 0.75];
gold = [0.96 0.75 0.36];
fig = dialog('Name','CleanLine','Position',[350 130 590 670], ...
    'Color',navy,'WindowStyle','modal','CloseRequestFcn',@cancel);
uicontrol(fig,'Style','text','String','CleanLine', ...
    'Position',[22 622 540 33],'BackgroundColor',navy, ...
    'ForegroundColor',white,'FontSize',19,'FontWeight','bold', ...
    'HorizontalAlignment','left');
uicontrol(fig,'Style','text', ...
    'String','Multitaper line-noise removal  |  Official V1 / V2 / optimized V2', ...
    'Position',[22 596 540 22],'BackgroundColor',navy, ...
    'ForegroundColor',teal,'HorizontalAlignment','left');
methods = {'Optimized V2','Original V2','Historical V1'};
methodsPopup = rowPopup('Implementation',methods,1,557);
modePopup = rowPopup('Execution mode (Optimized V2)',{'Serial','Parallel'},1,516);
typePopup = rowPopup('Signal type',{'Channels','Components'},1,475);
labels = {'Line frequencies (Hz)','Channel/component indices', ...
    'F-test p value','Scan bandwidth (Hz)','Taper bandwidth (Hz)', ...
    'Window length (s)','Window step (s)','Smoothing factor','FFT padding'};
defaults = {'60',sprintf('1:%d',EEG.nbchan),'0.01','2','2','4','1','100','2'};
edits = gobjects(1,numel(labels));
for k=1:numel(labels)
    y=432-(k-1)*37;
    uicontrol(fig,'Style','text','String',labels{k}, ...
        'Position',[24 y 270 24],'BackgroundColor',navy, ...
        'ForegroundColor',white,'HorizontalAlignment','left');
    edits(k)=uicontrol(fig,'Style','edit','String',defaults{k}, ...
        'Position',[305 y+2 255 25],'BackgroundColor',panel, ...
        'ForegroundColor',white,'HorizontalAlignment','left');
end
uicontrol(fig,'Style','text', ...
    'String','V2 cleans channels in continuous EEG. Choose Historical V1 for ICA components.', ...
    'Position',[22 91 550 25],'BackgroundColor',navy, ...
    'ForegroundColor',gold,'HorizontalAlignment','left');
uicontrol(fig,'Style','text','String', ...
    {'Mullen, CleanLine (2012)  |  Bigdely-Shamlo et al., PREP (2015)', ...
     'Maruyama et al., Cortex (2026), doi:10.1016/j.cortex.2026.11.005'}, ...
    'Position',[22 43 550 43],'BackgroundColor',navy, ...
    'ForegroundColor',teal,'HorizontalAlignment','left','FontSize',9);
uicontrol(fig,'Style','pushbutton','String','Cancel', ...
    'Position',[365 12 90 27],'Callback',@cancel);
uicontrol(fig,'Style','pushbutton','String','Clean data', ...
    'Position',[466 12 100 27],'BackgroundColor',teal, ...
    'Callback',@run);
uiwait(fig);

    function h = rowPopup(label, choices, initial, y)
        uicontrol(fig,'Style','text','String',label, ...
            'Position',[24 y 270 24],'BackgroundColor',navy, ...
            'ForegroundColor',white,'HorizontalAlignment','left');
        h=uicontrol(fig,'Style','popupmenu','String',choices, ...
            'Value',initial,'Position',[305 y+2 255 25], ...
            'BackgroundColor',panel,'ForegroundColor',white);
    end
    function cancel(~,~)
        if ishghandle(fig), delete(fig); end
    end
    function run(~,~)
        try
            frequency = str2num(get(edits(1),'String')); %#ok<ST2NM>
            channels = str2num(get(edits(2),'String')); %#ok<ST2NM>
            numeric = zeros(1,7);
            for j=1:7, numeric(j)=str2double(get(edits(j+2),'String')); end
            assert(~isempty(frequency) && ~isempty(channels) && ...
                all(isfinite(numeric)),'Enter valid numeric settings.');
            method={'optimized','original','legacy'};
            execution={'serial','parallel'};
            signal={'Channels','Components'};
            args={'Implementation',method{get(methodsPopup,'Value')}, ...
                'ExecutionMode',execution{get(modePopup,'Value')}, ...
                'SignalType',signal{get(typePopup,'Value')}, ...
                'LineFrequencies',frequency,'ChanCompIndices',channels, ...
                'LineAlpha',numeric(1),'Bandwidth',numeric(2), ...
                'TaperBandWidth',numeric(3),'SlidingWinLength',numeric(4), ...
                'SlidingWinStep',numeric(5),'SmoothingFactor',numeric(6), ...
                'PaddingFactor',numeric(7)};
            accepted=true;
            delete(fig);
        catch err
            errordlg(err.message,'CleanLine settings');
        end
    end
end
